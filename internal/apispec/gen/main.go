// Command gen writes the Docker Engine API route table from a swagger spec.
//
//	go run ./gen <spec.yaml> <output.go>
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"slices"
	"strings"

	"sigs.k8s.io/yaml"
)

type spec struct {
	Info struct {
		Version string `json:"version"`
	} `json:"info"`
	Paths map[string]map[string]any `json:"paths"`
}

var methods = []string{"get", "head", "post", "put", "patch", "delete"}

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: gen <spec.yaml> <output.go>")
	}
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	var s spec
	if err := yaml.Unmarshal(data, &s); err != nil {
		log.Fatalf("parse %s: %v", os.Args[1], err)
	}

	var routes []string
	for path, ops := range s.Paths {
		for method := range ops {
			if slices.Contains(methods, method) {
				routes = append(routes, fmt.Sprintf("{%q, %q},", strings.ToUpper(method), path))
			}
		}
	}
	slices.Sort(routes)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen from %s. DO NOT EDIT.\n\n", os.Args[1])
	fmt.Fprintf(&b, "package apispec\n\n")
	fmt.Fprintf(&b, "// Version is the Docker Engine API version of the pinned specification.\n")
	fmt.Fprintf(&b, "const Version = %q\n\n", s.Info.Version)
	fmt.Fprintf(&b, "var routes = []Route{\n%s\n}\n", strings.Join(routes, "\n"))
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(os.Args[2], src, 0o644); err != nil {
		log.Fatal(err)
	}
}
